import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import ts from 'typescript';
async function moduleAt(path){let source=readFileSync(path,'utf8');if(path.endsWith('capture-flow.ts')){const validation=ts.transpileModule(readFileSync('lib/validation.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;source=source.replace('"./validation"',JSON.stringify('data:text/javascript;base64,'+Buffer.from(validation).toString('base64')));}return import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText).toString('base64'));}
const {captureFileError,canContinueCapture}=await moduleAt('lib/capture-flow.ts');
